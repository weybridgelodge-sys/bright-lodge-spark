/**
 * While a list is open Radix marks the rest of the page aria-hidden but leaves it focusable
 * (axe: aria-hidden-focus). Make those same hidden regions `inert` too, and undo it on close
 * before Radix returns focus to the trigger (it does so on a later tick).
 */
function InertOutside() {
  React.useEffect(() => {
    const marked: HTMLElement[] = [];
    const t = window.setTimeout(() => {
      document.querySelectorAll<HTMLElement>('[data-aria-hidden="true"]').forEach((el) => {
        if (!el.hasAttribute("inert")) { el.setAttribute("inert", ""); marked.push(el); }
      });
    }, 0);
    return () => { window.clearTimeout(t); marked.forEach((el) => el.removeAttribute("inert")); };
  }, []);
  return null;
}

