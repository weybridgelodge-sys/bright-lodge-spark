import { expect, test } from "@playwright/test";
import { expectNoAxeViolations } from "./helpers/axe";

test("meeting card dining is £35 at 320px, with no fee choice", async ({ page }) => {
  const ev = { id: "ev1", slug: "test-meeting", title: "December Regular Meeting and Festive Board", intro: "Join us.", event_date: new Date(Date.now() + 30 * 864e5).toISOString(), published: true, archived_at: null, location: "Test Hall", tyling_time: "5pm", dining_time: "7pm" };
  await page.route("**/rest/v1/lodge_events**", r => r.fulfill({ json: [ev] }));
  await page.route("**/rest/v1/lodge_event_courses**", r => r.fulfill({ json: [] }));
  await page.route("**/rest/v1/lodge_event_dining_options**", r => r.fulfill({ json: [{ id: "d1", label: "Dining", price_pence: 3500, is_default: true }] }));
  await page.route("**/rest/v1/rpc/get_published_meeting_for_event**", r => r.fulfill({ json: [{ id: "m1", event_key: ev.slug }] }));
  await page.route("**/rest/v1/rpc/get_public_booking_details**", r => r.fulfill({ json: { lodge_name: "Sample Lodge", lodge_number: "1" } }));
  await page.route("**/rest/v1/module_settings**", r => r.fulfill({ json: [] }));
  await page.route(/\/src\/lib\/stripe\.ts/, r => r.fulfill({ contentType: "application/javascript", body: "const fake={elements(){},registerAppInfo(){},_registerWrapper(){},createEmbeddedCheckoutPage:async(o)=>{await o.fetchClientSecret();return {mount(){},unmount(){},destroy(){}};}};export const getStripe=()=>Promise.resolve(fake);export const getStripeEnvironment=()=>'sandbox';export const isPaymentsConfigured=()=>true;" }));
  const requests: any[] = [];
  await page.route("**/functions/v1/create-checkout", r => { requests.push(r.request().postDataJSON()); return r.fulfill({ json: { clientSecret: "test-only" } }); });
  await page.goto("/bookings?e2e_as=visitor");
  await page.locator("#evf-title").selectOption("Mr");
  await page.locator("#evf-first").fill("Bartholomew");
  await page.locator("#evf-last").fill("Montgomery-Smythe");
  await page.locator("#evf-email").fill("test@example.invalid");
  await page.locator("#evf-phone").fill("07000000000");
  await page.getByRole("button", { name: "Next" }).click();
  await page.locator("#evf-meeting").selectOption("meeting-and-festive-board");
  await page.getByRole("button", { name: "Next" }).click();
  await page.getByRole("radio", { name: /Debit/ }).check();
  await expect(page.getByText("£35.00", { exact: true })).toHaveCount(2);
  await expect(page.getByRole("radiogroup", { name: /fee/i })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(0);
  await expectNoAxeViolations(page, "meeting £35 card payment step");
  await page.getByRole("button", { name: "Continue to Payment" }).click();
  await expect(page.getByRole("heading", { name: "Secure Card Payment" })).toBeVisible();
  await expect(page.getByText("£35.00", { exact: true })).toHaveCount(1);
  await expect.poll(() => requests.length).toBeGreaterThan(0);
  expect(requests[0]).not.toHaveProperty("cover_fee");
  expect(requests[0].line_items).toMatchObject([{ qty: 1, unit_price_pence: 3500 }]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(0);
  await expectNoAxeViolations(page, "meeting no-fee checkout header");
  await page.screenshot({ path: "/tmp/browser/w2-meeting-checkout-320.png" });
});